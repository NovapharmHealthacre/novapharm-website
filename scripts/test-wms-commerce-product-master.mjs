import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildProductMaster,summariseProductMaster} from '../src/core/wms-commerce-product-master.mjs';
const read=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const sources={nutraxin:read('assets/data/nutraxin-retail-catalogue.json'),esco:read('assets/data/esco-catalogue.json'),connective:read('src/content/connective-consumer-research.json'),approvedConnective:read('src/content/approved-consumer-catalogue.json')};
const records=buildProductMaster(sources);
const report=summariseProductMaster(records);
assert.deepEqual(report.suppliers,{connective:395,esco:373,nutraxin:19});
assert.equal(report.total,787);
assert.equal(new Set(records.map(r=>r.sku)).size,787);
assert.equal(report.liveOfferCount,null);
assert(records.every(r=>r.stockQuantity===null&&r.checkoutStatus==='unverified_runtime'));
assert(records.filter(r=>r.supplier==='esco').every(r=>r.sourcePriceMinor===null));
assert(records.filter(r=>r.supplier==='connective').every(r=>r.sourcePriceMinor===null));
assert.equal(report.repositoryPriceCount,19);
assert.equal(report.approvedConnectiveContent,sources.approvedConnective.length);
assert.throws(()=>buildProductMaster({...sources,nutraxin:{products:[sources.nutraxin.products[0],sources.nutraxin.products[0]]}}),/duplicate SKU/);
assert.throws(()=>buildProductMaster({...sources,connective:{products:[{...sources.connective.products[0],sku:'invalid'}]}}),/Invalid Connective identity/);
assert.throws(()=>buildProductMaster({...sources,approvedConnective:[sources.approvedConnective[0],sources.approvedConnective[0]]}),/duplicate approved GTIN/);
console.log(JSON.stringify(report,null,2));
